const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('repository/apps/client/src/shared/lib/datetime.ts', 'utf8');
const start = source.indexOf('export function getUTCDateRange(');
const end = source.indexOf('\n}', start) + 2;
const helper = source.slice(start, end).replace('export ', '').replace('startISO: string, endISO: string): string[]', 'startISO, endISO)').replace('const dates: string[]', 'const dates');
const range = vm.runInNewContext(helper + '; getUTCDateRange');
const input = { start: '2026-09-30T00:00:00+09:00', end: '2026-10-02T00:00:00+09:00' };
const dates = Array.from(range(input.start, input.end));
assert.deepEqual(dates, ['2026-09-29','2026-09-30','2026-10-01']);
const localDate = value => { const date = new Date(value); return `${date.getFullYear()}-${String(date.getMonth()+1).padStart(2,'0')}-${String(date.getDate()).padStart(2,'0')}`; };
const homeFormat = value => { const date = new Date(value); return `${date.getMonth()+1}월 ${date.getDate()}일`; };
const schedule = '2026-10-02T09:00:00+09:00';
const cases = ['Asia/Seoul','UTC','America/Los_Angeles'].map(zone => { process.env.TZ=zone; return {zone, homeStart:homeFormat(input.start), homeEnd:homeFormat(input.end), listDates:dates, scheduleLocalDate:localDate(schedule), scheduleInListRange: dates.includes(localDate(schedule))}; });
assert.equal(cases[0].homeStart, '9월 30일');
assert.equal(cases[0].scheduleInListRange, false);
assert.equal(cases[1].homeStart, '9월 29일');
console.log(JSON.stringify({kind:'source-derived isolated date calculation; no app or database execution',input,schedule,cases,assertions:'passed'},null,2));
